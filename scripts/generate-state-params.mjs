// ============================================================================
// Generate src/data/generated/stateParams.ts from genshin-db.
//
// The numbers behind the character self-state toggles (data/selfStates.ts):
// Hu Tao's HP→ATK rate, Raiden's per-Energy Burst bonus and Resolve rates,
// Noelle's DEF→ATK rate. They live in talent attributes that are not damage
// rows, and some share one label between two parameters — Raiden's
// "Resolve Bonus|{param2} Initial/{param3} ATK DMG Per Stack" — which the
// per-hit table (generate-talents.mjs) folds into one number. So each value is
// read here by label and parameter position, all 15 talent levels.
//
// Also emitted: how many parameters each Burst damage label carries
// ("4-Hit DMG|{param8}+{param9}" = 2 parts), because a per-hit bonus such as
// Resolve applies once per part.
//
// Run: node scripts/generate-state-params.mjs
// ============================================================================

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const gdb = require('genshin-db');

/** [character id, genshin-db name, talent, label, parameter position in the label, output key] */
const SPEC = [
  ['hu-tao', 'Hu Tao', 'combat2', 'ATK Increase', 0, 'atkFromHP'],
  ['raiden-shogun', 'Raiden Shogun', 'combat2', 'Elemental Burst DMG Bonus', 0, 'burstBonusPerEnergy'],
  ['raiden-shogun', 'Raiden Shogun', 'combat3', 'Resolve Bonus', 0, 'resolveInitial'],
  ['raiden-shogun', 'Raiden Shogun', 'combat3', 'Resolve Bonus', 1, 'resolvePerHit'],
  ['raiden-shogun', 'Raiden Shogun', 'combat3', 'Energy Cost', 0, 'burstEnergyCost'],
  ['noelle', 'Noelle', 'combat3', 'ATK Bonus', 0, 'atkFromDEF'],
];

/** Burst labels whose parameter count we need, by character. */
const PARTS = [['raiden-shogun', 'Raiden Shogun']];

const paramsOf = (format) => [...format.matchAll(/\{(param\d+)[^}]*\}/g)].map((m) => m[1]);

function attribute(name, talent, label) {
  const t = gdb.talents(name)?.[talent];
  if (!t?.attributes) throw new Error(`${name} ${talent}: no attributes`);
  const line = t.attributes.labels.find((l) => l.split('|')[0] === label);
  if (!line) throw new Error(`${name} ${talent}: no label "${label}"`);
  return { format: line.split('|')[1], parameters: t.attributes.parameters };
}

const values = {};
for (const [id, name, talent, label, pos, key] of SPEC) {
  const { format, parameters } = attribute(name, talent, label);
  const param = paramsOf(format)[pos];
  if (!param) throw new Error(`${name} ${talent} "${label}": no parameter #${pos}`);
  const series = parameters[param];
  if (!Array.isArray(series) || series.length < 15) throw new Error(`${name} ${param}: expected 15 levels`);
  (values[id] ??= {})[key] = series.slice(0, 15).map((v) => Number(v.toFixed(6)));
}

const parts = {};
for (const [id, name] of PARTS) {
  const t = gdb.talents(name).combat3;
  parts[id] = Object.fromEntries(
    t.attributes.labels.map((l) => {
      const [label, format] = l.split('|');
      return [label, paramsOf(format).length];
    }),
  );
}

const out = `// AUTO-GENERATED by scripts/generate-state-params.mjs from genshin-db — do not edit.
// Talent parameters behind the self-state toggles, 15 talent levels each.

export const STATE_PARAMS: Record<string, Record<string, number[]>> = ${JSON.stringify(values, null, 2)};

/** Parameter count per Elemental Burst label (a "+"-joined label has several parts). */
export const BURST_LABEL_PARTS: Record<string, Record<string, number>> = ${JSON.stringify(parts, null, 2)};
`;
writeFileSync(join(root, 'src/data/generated/stateParams.ts'), out);
console.log('wrote src/data/generated/stateParams.ts');

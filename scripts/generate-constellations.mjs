// ============================================================================
// Generate src/data/generated/constellations.ts from genshin-db.
//
// Text for every character's six constellations and ascension passives. The
// descriptions are shown in the UI; whether a constellation is applied to the
// damage model is decided by the curated map in src/data/constellations.ts.
//
// Run: node scripts/generate-constellations.mjs
// ============================================================================

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const gdb = require('genshin-db');

const charactersSrc = readFileSync(join(root, 'src/data/characters.ts'), 'utf8');
const ROSTER = charactersSrc
  .split('\n')
  .map((line) => line.match(/\{ id: '([^']+)', name: '([^']+)'/))
  .filter(Boolean)
  .map((m) => ({ id: m[1], name: m[2] }));

const constellations = {};
const passives = {};
const missing = [];

for (const c of ROSTER) {
  let cons;
  let talents;
  try {
    cons = gdb.constellations(c.name);
    talents = gdb.talents(c.name);
  } catch {
    cons = null;
  }
  if (!cons || !talents) {
    missing.push(`${c.id} (${c.name})`);
    continue;
  }

  constellations[c.id] = [1, 2, 3, 4, 5, 6]
    .map((level) => {
      const entry = cons[`c${level}`];
      if (!entry) return null;
      return { level, name: entry.name ?? '', description: entry.description ?? '' };
    })
    .filter(Boolean);

  passives[c.id] = Object.keys(talents)
    .filter((k) => /^passive\d+$/.test(k))
    .map((k) => talents[k])
    .filter(Boolean)
    .map((p) => ({ name: p.name ?? '', description: p.description ?? '' }));
}

const outDir = join(root, 'src/data/generated');
mkdirSync(outDir, { recursive: true });

const banner = `// ============================================================================
// AUTO-GENERATED by scripts/generate-constellations.mjs — DO NOT EDIT BY HAND.
// Constellation and ascension-passive text for every character, from genshin-db
// (${Object.keys(constellations).length} characters).
// ============================================================================
`;

const body = `export interface ConstellationEntry {
  level: number;
  name: string;
  description: string;
}

export interface PassiveEntry {
  name: string;
  description: string;
}

export const CONSTELLATIONS: Record<string, ConstellationEntry[]> = ${JSON.stringify(constellations, null, 0)};

export const PASSIVES: Record<string, PassiveEntry[]> = ${JSON.stringify(passives, null, 0)};

export function constellationsFor(id: string): ConstellationEntry[] | undefined {
  return CONSTELLATIONS[id];
}

export function passivesFor(id: string): PassiveEntry[] | undefined {
  return PASSIVES[id];
}
`;

writeFileSync(join(outDir, 'constellations.ts'), banner + body);
console.log(`characters: ${Object.keys(constellations).length}/${ROSTER.length}`);
if (missing.length) console.log(`MISSING (${missing.length}): ${missing.join(', ')}`);

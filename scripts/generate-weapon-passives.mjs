// ============================================================================
// Generate src/data/generated/weaponPassives.ts from genshin-db.
//
// For every weapon listed in src/data/weapons.ts we pull the passive name, the
// template, and the five refinement descriptions with their extracted values.
// Passive text is shown verbatim in the UI; whether a passive is applied to the
// damage model is decided by the curated map in src/data/weaponPassives.ts.
//
// Run: node scripts/generate-weapon-passives.mjs
// ============================================================================

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const gdb = require('genshin-db');

const weaponsSrc = readFileSync(join(root, 'src/data/weapons.ts'), 'utf8');
const WEAPONS = [...weaponsSrc.matchAll(/\{ id: '([^']+)', name: "([^"]+)"/g)].map((m) => ({ id: m[1], name: m[2] }));

const table = {};
const missing = [];

for (const w of WEAPONS) {
  let data;
  try {
    data = gdb.weapons(w.name);
  } catch {
    data = null;
  }
  if (!data) {
    missing.push(`${w.id} (${w.name})`);
    continue;
  }
  const refinements = ['r1', 'r2', 'r3', 'r4', 'r5'].map((k) => data[k]).filter(Boolean);
  table[w.id] = {
    id: w.id,
    name: data.name,
    effectName: data.effectName ?? '',
    templateRaw: data.effectTemplateRaw ?? '',
    refinements: refinements.map((r) => ({ description: r.description, values: r.values ?? [] })),
  };
}

const outDir = join(root, 'src/data/generated');
mkdirSync(outDir, { recursive: true });

const banner = `// ============================================================================
// AUTO-GENERATED by scripts/generate-weapon-passives.mjs — DO NOT EDIT BY HAND.
// Passive name, template and the five refinement descriptions for every weapon
// in src/data/weapons.ts, from genshin-db (${Object.keys(table).length} weapons).
// ============================================================================
`;

const body = `export interface WeaponRefinement {
  description: string;
  values: string[];
}

export interface WeaponPassiveData {
  id: string;
  name: string;
  effectName: string;
  templateRaw: string;
  /** r1..r5 */
  refinements: WeaponRefinement[];
}

export const WEAPON_PASSIVES: Record<string, WeaponPassiveData> = ${JSON.stringify(table, null, 0)};

export function weaponPassiveFor(id: string): WeaponPassiveData | undefined {
  return WEAPON_PASSIVES[id];
}
`;

writeFileSync(join(outDir, 'weaponPassives.ts'), banner + body);
console.log(`weapons: ${Object.keys(table).length}/${WEAPONS.length}`);
if (missing.length) console.log(`MISSING (${missing.length}): ${missing.join(', ')}`);

// ============================================================================
// Generate src/data/generated/constellationTalents.ts.
//
// C3 and C5 always read "Increases the Level of <talent> by 3". We resolve the
// combat talent names (combat1/2/3) from genshin-db and map the <talent> in the
// text to normal / skill / burst, so the calculator can auto-apply the +3 when
// the user picks C3 / C5.
//
// Run: node scripts/generate-constellation-talents.mjs
// ============================================================================

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const gdb = require('genshin-db');

const charactersSrc = readFileSync(join(root, 'src/data/characters.ts'), 'utf8');
const ROSTER = charactersSrc
  .split('\n')
  .map((line) => line.match(/\{ id: '([^']+)', name: '([^']+)'/))
  .filter(Boolean)
  .map((m) => ({ id: m[1], name: m[2] }));

const norm = (s) => String(s).toLowerCase().replace(/[^a-z0-9]+/g, '');

const table = {};
const missing = [];

for (const c of ROSTER) {
  let t;
  let cons;
  try {
    t = gdb.talents(c.name);
    cons = gdb.constellations(c.name);
  } catch {
    continue;
  }
  if (!t || !cons) {
    missing.push(c.id);
    continue;
  }
  const names = {
    normal: t.combat1?.name ?? '',
    skill: t.combat2?.name ?? '',
    burst: t.combat3?.name ?? '',
  };
  const entry = {};
  for (const level of [3, 5]) {
    const desc = cons[`c${level}`]?.description ?? '';
    const m = desc.match(/Increases the Level of (.+?) by 3/i);
    if (!m) continue;
    const target = norm(m[1]);
    const hit = (['normal', 'skill', 'burst']).find((k) => norm(names[k]) === target || target.includes(norm(names[k])) || norm(names[k]).includes(target));
    if (hit) entry[level] = hit;
  }
  if (Object.keys(entry).length) table[c.id] = entry;
}

const outDir = join(root, 'src/data/generated');
mkdirSync(outDir, { recursive: true });

const banner = `// ============================================================================
// AUTO-GENERATED by scripts/generate-constellation-talents.mjs — DO NOT EDIT.
// Which combat talent each character's C3 / C5 raises by +3.
// ============================================================================
`;

const body = `export type TalentBucket = 'normal' | 'skill' | 'burst';

/** charId -> { 3?: bucket, 5?: bucket } — the talent C3 / C5 boost by 3. */
export const CONSTELLATION_TALENT_BONUS: Record<string, Partial<Record<3 | 5, TalentBucket>>> = ${JSON.stringify(table, null, 0)};
`;

writeFileSync(join(outDir, 'constellationTalents.ts'), banner + body);
console.log(`characters with a C3/C5 talent bonus: ${Object.keys(table).length}/${ROSTER.length}`);
if (missing.length) console.log(`missing: ${missing.join(', ')}`);

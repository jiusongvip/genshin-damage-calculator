describe('site-wide — invariants the Diff-mode baseline depends on', () => {
  // A baseline keys rows by id, so ids must be unique within a character —
  // otherwise two different hits would collapse onto one comparison.
  it('talent row ids are unique within every character', () => {
    const collisions: string[] = [];
    for (const c of CHARACTERS) {
      const rows = talentRowsFor(c.id);
      if (!rows) continue;
      const seen = new Set<string>();
      for (const r of rows) {
        if (seen.has(r.id)) collisions.push(`${c.id}:${r.id}`);
        seen.add(r.id);
      }
    }
    expect(collisions).toEqual([]);
  });

  // ...but they are NOT namespaced by character: generated ids look like
  // "combat1-0-1-hit-dmg" and repeat verbatim across characters. That is why a
  // baseline has to carry the character it was pinned on and be ignored
  // elsewhere — otherwise it would match row-for-row and report garbage rather
  // than failing loudly.
  it('row ids repeat across characters, so a baseline must be character-scoped', () => {
    const baizhuIds = new Set(talentRowsFor('baizhu')!.map((r) => r.id));
    const shared = talentRowsFor('ganyu')!.filter((r) => baizhuIds.has(r.id)).map((r) => r.id);
    expect(shared).toContain('combat1-0-1-hit-dmg');
  });
});


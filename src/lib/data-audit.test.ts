/**
 * The generators are the only writers of levelStats.ts and characters.ts, so
 * the two must agree. These assertions fail loudly if either drifts again.
 */
describe('site-wide — generated data agrees with itself', () => {
  it('characters.ts base stats equal the level-90 curve', () => {
    const drift = [];
    for (const c of CHARACTERS) {
      const curve = baseStatsAt(c.id, 90);
      if (!curve) { drift.push(`${c.id}: no curve`); continue; }
      if (Math.abs(curve.hp - c.baseHP) > 1e-4) drift.push(`${c.id}: hp ${c.baseHP} vs ${curve.hp}`);
      if (Math.abs(curve.atk - c.baseATK) > 1e-4) drift.push(`${c.id}: atk ${c.baseATK} vs ${curve.atk}`);
      if (Math.abs(curve.def - c.baseDEF) > 1e-4) drift.push(`${c.id}: def ${c.baseDEF} vs ${curve.def}`);
    }
    expect(drift).toEqual([]);
  });

  it('ascension.value is the raw level-90 curve value, not the bonus alone', () => {
    // lib/damage.ts subtracts the baked-in base (0.05 CR / 0.5 CD) from
    // curve.spec. `value` is only a fallback, but it must speak the same
    // language or a missing curve would double-count.
    const drift = [];
    for (const c of CHARACTERS) {
      const curve = baseStatsAt(c.id, 90)!;
      if (Math.abs(curve.spec - c.ascension.value) > 1e-4) {
        drift.push(`${c.id}: value ${c.ascension.value} vs curve ${curve.spec}`);
      }
    }
    expect(drift).toEqual([]);
  });

  it('Lauma really has 115.2 EM, not the 315 she used to carry', () => {
    const lauma = CHARACTERS.find((c) => c.id === 'lauma')!;
    expect(lauma.ascension.type).toBe('em');
    expect(lauma.ascension.value).toBeCloseTo(115.2, 6);
  });

  it('row.scaling honours an explicit stat in the format string', () => {
    // The dataset spells out the stat when it is not ATK, e.g.
    // "Breakthrough Barb DMG|{param7:F2P} Max HP". Those rows used to be
    // multiplied by ATK.
    const row = (id: string, label: string, group?: string) =>
      talentRowsFor(id)!.find((r) => r.label === label && (!group || r.group === group))!;
    expect(row('yelan', 'Breakthrough Barb DMG').scaling).toBe('hp');
    expect(row('columbina', 'Moondew Cleanse DMG').scaling).toBe('hp');
    expect(row('kuki-shinobu', 'Single Instance DMG').scaling).toBe('hp');
    expect(row('xilonen', 'Blade Roller 1-Hit DMG').scaling).toBe('def');
    // Gorou has a "Skill DMG" in both the skill and the burst talent; only the
    // burst one carries the DEF suffix.
    expect(row('gorou', 'Skill DMG', 'burst').scaling).toBe('def');
    expect(row('yun-jin', 'Charge Level 2 DMG').scaling).toBe('def');
    expect(row('zibai', "Spirit Steed's Stride 1-Hit DMG").scaling).toBe('def');
    expect(row('linnea', 'Lumi Million Ton Crush DMG').scaling).toBe('def');
    expect(row('nefer', 'Phantasm Performance 3-Hit DMG (Shades)').scaling).toBe('em');
    expect(row('lauma', '2-Hit Hold DMG').scaling).toBe('em');
  });

  it('dual-stat rows keep a single-stat fallback rather than dropping a term', () => {
    // "ATK+Elemental Mastery" needs both; one `scaling` field cannot express
    // it, so these deliberately stay on the group-derived value.
    const alhaitham = talentRowsFor('alhaitham')!.find((r) => r.label === 'Rush Attack DMG')!;
    expect(alhaitham.scaling).toBe('atk');
    const dehya = talentRowsFor('dehya')!.find((r) => r.label === 'Flame-Mane\'s Fist DMG')!;
    expect(dehya.scaling).toBe('atk');
  });
});


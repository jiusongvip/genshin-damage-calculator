    const atC6 = signatureMultiplierAt('baizhu', 'burst', effectiveTalentLevels('baizhu', levels, 6));
    expect(atC6).not.toBe(atC0);
    expect(withMult(atC6)).toBeGreaterThan(withMult(atC0));

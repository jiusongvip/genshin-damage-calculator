describe('Baizhu — which talent the site treats as his signature', () => {
  it('the engine picks the Normal Attack combo, not his Burst', () => {
    const sig = signatureTalent('baizhu')!;
    expect(sig.key).toBe('normal');
    // 3.114, not the 2.709 the hand-committed table carried: the summary is now
    // generated from the per-hit rows, so the ×2 on his 3-Hit reaches it.
    expect(sig.multiplier).toBeCloseTo(3.114, 3);
  });

  it('the summary table agrees with the per-hit table', () => {
    // The invariant that makes both files safe to regenerate: TALENTS is
    // derive(generated/talents.ts). scripts/generate-talents-summary.mjs writes
    // it that way, and npm run check:data re-derives it independently.
    const rows = talentRowsFor('baizhu')!;
    const combo = rows
      .filter((r) => r.isDamage && r.group === 'normal')
      .reduce((s, r) => s + r.values[9] * r.hits, 0);
    expect(combo).toBeCloseTo(TALENTS['baizhu'].normal, 3);
    expect(TALENTS['baizhu'].normal).toBeCloseTo(3.114, 3);
  });

  it('characters.ts advertises a Burst that is never used', () => {
    // signatureTalent() always resolves for baizhu, so skillName/skillMultiplier
    // are dead fallbacks — and they contradict what the engine actually does.
    expect(baizhu.skillName).toBe('Holistic Revivification (Burst)');
    expect(baizhu.skillMultiplier).toBe(1.6);
    // Neither 1.6 nor the burst's 1.747 is what the engine multiplies by.
    expect(signatureTalent('baizhu')!.multiplier).not.toBeCloseTo(baizhu.skillMultiplier, 3);
  });
});


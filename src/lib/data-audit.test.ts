const baizhu = CHARACTERS.find((c) => c.id === 'baizhu')!;
const enemy = ENEMIES[0];

describe('Baizhu — base stats agree with all three sources', () => {
  it('level 90 base HP / ATK / DEF match genshin-db', () => {
    // genshin-db stats(90): hp 13348.0427932 / attack 192.5385949 / defense 499.5603405
    // aspirine hp_base 1039.1188 + curve; paimon identical base + promotion table.
    const curve = baseStatsAt('baizhu', 90)!;
    expect(Math.round(curve.hp)).toBe(13348);
    expect(Math.round(curve.atk * 100) / 100).toBe(192.54);
    expect(Math.round(curve.def)).toBe(500);
  });

  it('ascension stat is HP% and the true value is 0.288', () => {
    expect(baizhu.ascension.type).toBe('hp%');
    expect(baizhu.ascension.value).toBeCloseTo(0.288, 3);
  });

  it('the level curve keeps the ascension stat at full precision', () => {
    const curve = baseStatsAt('baizhu', 90)!;
    // All three sources report 28.8%, not 29%. FIXED 2026-09-21: the curve is
    // now generated by scripts/generate-level-stats.mjs and no longer rounded
    // to 2 dp, so every step is exact: 0.072 / 0.144 / 0.216 / 0.288.
    expect(curve.spec).toBeCloseTo(0.288, 6);
    expect(curve.spec).not.toBeCloseTo(0.29, 4);
    const steps = [41, 51, 71, 81].map((lv) => baseStatsAt('baizhu', lv)!.spec);
    expect(steps).toEqual([0.072, 0.144, 0.216, 0.288]);
  });

  it('scaling is HP (skill + burst both scale off Max HP)', () => {
    expect(baizhu.scaling).toBe('hp');
  });
});

